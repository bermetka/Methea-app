"""Regenerate content/theories/index.ts from the card JSON files. Run from the repo root."""
import json, glob, os
files = sorted(f for f in glob.glob('content/theories/*.json') if not f.endswith('_template.json'))
lines = ["// Generated by scripts/theory-content/gen_index.py: do not edit by hand.",
         "import type { TheoryCardContent } from '@/lib/literature/theory-content'", ""]
names = []
for f in files:
    slug = os.path.basename(f)[:-5]; var = slug.replace('-', '_')
    names.append((json.load(open(f))['library_name'], var))
    lines.append(f"import {var} from './{slug}.json'")
lines += ["", "export const THEORY_CARDS: Record<string, TheoryCardContent> = {"]
lines += [f"  {json.dumps(n)}: {v} as unknown as TheoryCardContent," for n, v in names]
lines += ["}"]
open('content/theories/index.ts', 'w').write("\n".join(lines) + "\n")
print(len(names), "cards")
